// Build-time step: reads the expert team from this repository and generates
//   src/generated/team.json             - public data for the browser (no prompts)
//   netlify/lib/generated/team-data.mjs - full prompts, skills, knowledge and research for the functions
//
// Sources (relative to the repo root):
//   .claude/agents/*.md            agent definitions (frontmatter + system prompt)
//   .claude/skills/<name>/SKILL.md skills preloaded by each agent
//   knowledge/<agent-name>/*       each agent's knowledge folder
//   docs/*.md                      shared research
import { readFileSync, readdirSync, statSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join, dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ROOT = resolve(WEB, "..");
const AGENTS_DIR = join(ROOT, ".claude", "agents");
const SKILLS_DIR = join(ROOT, ".claude", "skills");
const KNOWLEDGE_DIR = join(ROOT, "knowledge");
const DOCS_DIR = join(ROOT, "docs");
const TEXT_EXT = /\.(md|markdown|txt|csv|json|ya?ml)$/i;

// Research every agent receives (shared prefix, so it caches across agents on the same model).
const RESEARCH = ["README.md", "01-market.md", "02-target-customers.md", "03-competitors.md",
  "04-startup-and-operating-costs.md", "05-permits-and-licenses.md", "06-staffing.md",
  "07-marketing.md", "08-risks.md"];

const DOMAIN_ORDER = ["Coordination", "Business", "Technical", "Operations", "Finance", "Legal", "Marketing", "Risk", "Support"];

function split(path) {
  const text = readFileSync(path, "utf8");
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  if (!m) throw new Error(`No frontmatter: ${path}`);
  return { meta: YAML.parse(m[1]) ?? {}, body: m[2].trim() };
}

function readTextFiles(dir) {
  if (!existsSync(dir)) return [];
  const out = [];
  const walk = (d) => {
    for (const name of readdirSync(d).sort()) {
      const p = join(d, name);
      if (statSync(p).isDirectory()) { if (name !== "archive") walk(p); continue; }
      if (TEXT_EXT.test(name)) out.push({ path: relative(ROOT, p), text: readFileSync(p, "utf8").trim() });
    }
  };
  walk(dir);
  return out;
}

const pick = (body, re) => (body.match(re) || [])[1]?.trim() ?? "";

// ---- skills
const skills = {};
for (const name of readdirSync(SKILLS_DIR).sort()) {
  const p = join(SKILLS_DIR, name, "SKILL.md");
  if (!existsSync(p)) continue;
  const { meta, body } = split(p);
  skills[name] = { description: meta.description ?? "", body };
}

// ---- agents
const agents = {};
const publicAgents = [];
for (const file of readdirSync(AGENTS_DIR).filter((f) => f.endsWith(".md")).sort()) {
  const { meta, body } = split(join(AGENTS_DIR, file));
  const name = meta.name;
  const title = pick(body, /^# (.+)$/m);
  const firstName = pick(body, /\*\*Name:\*\*\s*(\w+)/) || title;
  const voice = pick(body, /\*\*Voice:\*\*\s*(.+)/);
  const style = pick(body, /\*\*Working style:\*\*\s*(.+)/);
  const domain = name === "orchestrator" || name === "team-architect"
    ? "Support"
    : pick(body, /\(roster A\d+, (\w+) domain\)/) || "Other";
  const preload = Array.isArray(meta.skills) ? meta.skills : [];
  const missing = preload.filter((s) => !skills[s]);
  if (missing.length) throw new Error(`${name}: missing skills ${missing.join(", ")}`);
  const knowledge = readTextFiles(join(KNOWLEDGE_DIR, name));
  const description = String(meta.description ?? "").split(" Delegate to this expert for:")[0];

  agents[name] = { name, title, firstName, model: meta.model ?? "sonnet", prompt: body, skills: preload, knowledge };
  publicAgents.push({
    name, title, firstName, voice, style, domain,
    model: meta.model ?? "sonnet", color: meta.color ?? "blue", description,
    knowledgeFiles: knowledge.map((k) => k.path.replace(`knowledge/${name}/`, "")),
  });
}
if (!agents.orchestrator) throw new Error("orchestrator agent not found");

publicAgents.sort((a, b) =>
  (DOMAIN_ORDER.indexOf(a.domain) - DOMAIN_ORDER.indexOf(b.domain)) || a.firstName.localeCompare(b.firstName));

// ---- research
const research = RESEARCH.filter((f) => existsSync(join(DOCS_DIR, f)))
  .map((f) => ({ path: `docs/${f}`, text: readFileSync(join(DOCS_DIR, f), "utf8").trim() }));

// ---- write outputs
const pubDir = join(WEB, "src", "generated");
const libDir = join(WEB, "netlify", "lib", "generated");
mkdirSync(pubDir, { recursive: true });
mkdirSync(libDir, { recursive: true });

writeFileSync(join(pubDir, "team.json"), JSON.stringify({
  builtAt: new Date().toISOString(),
  domains: DOMAIN_ORDER,
  agents: publicAgents,
}, null, 2) + "\n");

writeFileSync(join(libDir, "team-data.mjs"),
  "// Generated by scripts/build-team.mjs. Do not edit.\n" +
  `export default ${JSON.stringify({ agents, skills, research })};\n`);

const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(0)} KB`;
console.log(`build-team: ${publicAgents.length} agents, ${Object.keys(skills).length} skills, ` +
  `${research.length} research docs, ${publicAgents.reduce((n, a) => n + a.knowledgeFiles.length, 0)} knowledge files ` +
  `(${kb(readFileSync(join(libDir, "team-data.mjs"), "utf8"))} server data)`);
